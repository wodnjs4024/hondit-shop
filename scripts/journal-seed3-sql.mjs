// Writes supabase/seeds/012_journal_batch3.sql from shared/journal-seed-3.js so the SQL and the code never drift.
// The rows are inserted as in_review (not public). Re-running changes nothing (on conflict do nothing).
// Usage: node scripts/journal-seed3-sql.mjs
import { writeFileSync } from 'node:fs';
import { seedArticles3 } from '../shared/journal-seed-3.js';

const lit = (v) => v === null || v === undefined ? 'null' : Array.isArray(v) && v.every((x) => typeof x === 'string')
  ? `array[${v.map((x) => lit(x)).join(',')}]::text[]` : typeof v === 'object' ? `${lit(JSON.stringify(v))}::jsonb` : `'${String(v).replaceAll("'", "''")}'`;
const rows = seedArticles3.map((row) => {
  const cols = Object.keys(row).filter((k) => row[k] !== undefined && row[k] !== null);
  const values = cols.map((k) => (k === 'sources' ? `${lit(JSON.stringify(row[k]))}::jsonb` : lit(row[k])));
  return `insert into public.journal_articles (${cols.join(', ')})\nvalues (${values.join(', ')})\non conflict (content_id) do nothing;`;
}).join('\n\n');
const sql = `-- Generated by scripts/journal-seed3-sql.mjs. Inserts journal batch 3 (4 articles) as in_review, not public.
-- Needs migrations 010 and 011. Re-running changes nothing.
begin;
${rows}

insert into public.journal_publish_log (article_id, action, message, actor)
select id, 'created', 'Batch 3 seeded (2026-11-12), in_review', 'seed-012'
from public.journal_articles a
where a.content_id in ('S-JRN-SG-03','S-JRN-JP-03','S-JRN-HK-03','S-JRN-TW-03')
  and not exists (select 1 from public.journal_publish_log l where l.article_id = a.id);
commit;
`;
writeFileSync(new URL('../supabase/seeds/012_journal_batch3.sql', import.meta.url), sql);
console.log('wrote supabase/seeds/012_journal_batch3.sql');
