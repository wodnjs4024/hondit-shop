// Writes supabase/seeds/011_journal_batch2.sql from shared/journal-seed-2.js so the SQL and the code never drift.
// Usage: node scripts/journal-batch2-sql.mjs
import { writeFileSync } from 'node:fs';
import { seedArticles2 } from '../shared/journal-seed-2.js';

const lit = (v) => v === null || v === undefined ? 'null' : Array.isArray(v) && v.every((x) => typeof x === 'string') && !v.some((x) => typeof x === 'object')
  ? `array[${v.map((x) => lit(x)).join(',')}]::text[]` : typeof v === 'object' ? `${lit(JSON.stringify(v))}::jsonb` : `'${String(v).replaceAll("'", "''")}'`;
const insert = (table, rows, conflict) => rows.map((row) => {
  const cols = Object.keys(row).filter((k) => row[k] !== undefined);
  const values = cols.map((k) => (k === 'sources' ? `${lit(JSON.stringify(row[k]))}::jsonb` : lit(row[k])));
  return `insert into public.${table} (${cols.join(', ')})\nvalues (${values.join(', ')})\non conflict (${conflict}) do nothing;`;
}).join('\n\n');

const sql = `-- Generated by scripts/journal-batch2-sql.mjs. Inserts the second article batch (status in_review, not public).
-- Re-running changes nothing.
${insert('journal_articles', seedArticles2, 'content_id')}

insert into public.journal_publish_log (article_id, action, message, actor)
select id, 'created', 'Seeded second batch (review pending)', 'seed-011'
from public.journal_articles a
where a.content_id in (${seedArticles2.map((a) => `'${a.content_id}'`).join(', ')})
  and not exists (select 1 from public.journal_publish_log l where l.article_id = a.id);
`;
writeFileSync(new URL('../supabase/seeds/011_journal_batch2.sql', import.meta.url), sql);
console.log('wrote supabase/seeds/011_journal_batch2.sql');
