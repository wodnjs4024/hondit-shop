// Writes supabase/seeds/013_journal_batch3_photos.sql: swaps the photos (and body markdown) of batch 3
// on rows that are still in_review. Rows already approved/published are not touched.
// Usage: node scripts/journal-seed3-photos-sql.mjs
import { writeFileSync } from 'node:fs';
import { seedArticles3 } from '../shared/journal-seed-3.js';

const lit = (v) => `'${String(v).replaceAll("'", "''")}'`;
const stmts = seedArticles3.map((r) => `update public.journal_articles set
  hero_image_url = ${lit(r.hero_image_url)}, hero_image_alt = ${lit(r.hero_image_alt)},
  hero_image_caption = ${lit(r.hero_image_caption)}, hero_image_credit = ${lit(r.hero_image_credit)},
  body_md = ${lit(r.body_md)}
where content_id = ${lit(r.content_id)} and status = 'in_review';`).join('\n\n');
writeFileSync(new URL('../supabase/seeds/013_journal_batch3_photos.sql', import.meta.url),
`-- Generated by scripts/journal-seed3-photos-sql.mjs. Swaps batch 3 photos; only rows still in_review.
begin;
${stmts}
commit;
`);
console.log('wrote supabase/seeds/013_journal_batch3_photos.sql');
