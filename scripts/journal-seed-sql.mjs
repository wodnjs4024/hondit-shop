// Writes supabase/seeds/010_journal_seed.sql from shared/journal-seed.js so the SQL and the code never drift.
// Usage: node scripts/journal-seed-sql.mjs
import { writeFileSync } from 'node:fs';
import { seedArticles, seedPress } from '../shared/journal-seed.js';

const lit = (v) => v === null || v === undefined ? 'null' : Array.isArray(v) && v.every((x) => typeof x === 'string') && !v.some((x) => typeof x === 'object')
  ? `array[${v.map((x) => lit(x)).join(',')}]::text[]` : typeof v === 'object' ? `${lit(JSON.stringify(v))}::jsonb` : `'${String(v).replaceAll("'", "''")}'`;
const insert = (table, rows, conflict) => rows.map((row) => {
  const cols = Object.keys(row).filter((k) => row[k] !== undefined);
  const values = cols.map((k) => (k === 'sources' ? `${lit(JSON.stringify(row[k]))}::jsonb` : lit(row[k])));
  return `insert into public.${table} (${cols.join(', ')})\nvalues (${values.join(', ')})\non conflict (${conflict}) do nothing;`;
}).join('\n\n');

const sql = `-- Generated by scripts/journal-seed-sql.mjs. Inserts the four existing country drafts (status in_review, not public)
-- and the five existing press-outreach drafts (approval pending, not sent). Re-running changes nothing.
${insert('journal_articles', seedArticles, 'content_id')}

${insert('pr_outreach', seedPress, 'content_id')}

insert into public.journal_publish_log (article_id, action, message, actor)
select id, 'created', 'Seeded from HONDIT_무료PR_기사초안_4개국_20261023 (review pending)', 'seed-010'
from public.journal_articles a
where a.content_id like 'S-JRN-%' and not exists (select 1 from public.journal_publish_log l where l.article_id = a.id);
`;
writeFileSync(new URL('../supabase/seeds/010_journal_seed.sql', import.meta.url), sql);
console.log('wrote supabase/seeds/010_journal_seed.sql');
