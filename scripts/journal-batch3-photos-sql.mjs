// Writes supabase/seeds/013_journal_batch3_photos.sql: puts the batch 3 photo swap (shared/journal-seed-3.js) into rows
// that were already inserted by 012. Only hero image fields and body_md change, and only while the row is still in_review.
// Usage: node scripts/journal-batch3-photos-sql.mjs
import { writeFileSync, existsSync } from 'node:fs';
import { seedArticles3 } from '../shared/journal-seed-3.js';

const q = (v) => `'${String(v).replaceAll("'", "''")}'`;
const onDisk = (src) => existsSync(new URL(`../public${src}`, import.meta.url));
const updates = seedArticles3.map((a) => {
  const images = [a.hero_image_url, ...[...a.body_md.matchAll(/!\[[^\]]*\]\(([^ )]+)/g)].map((m) => m[1])];
  for (const src of images) if (!onDisk(src)) throw new Error(`${a.content_id}: missing image ${src}`);
  return `update public.journal_articles set hero_image_url = ${q(a.hero_image_url)}, hero_image_alt = ${q(a.hero_image_alt)},
  hero_image_caption = ${q(a.hero_image_caption)}, hero_image_credit = ${q(a.hero_image_credit)}, body_md = ${q(a.body_md)}
where content_id = ${q(a.content_id)} and status = 'in_review';`;
}).join('\n\n');
writeFileSync(new URL('../supabase/seeds/013_journal_batch3_photos.sql', import.meta.url), `-- Generated by scripts/journal-batch3-photos-sql.mjs. Swaps batch 3 photos for ones not used in earlier Journal articles.
-- Rows stay in_review (nothing is published). Re-running changes nothing new.
begin;
${updates}
commit;
`);
console.log('wrote supabase/seeds/013_journal_batch3_photos.sql');
